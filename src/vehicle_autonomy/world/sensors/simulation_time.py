"""Owned Gazebo public Clock generation times -> conservative host bounds.

Clock.system is generated by Gazebo's system_clock at publication (official
SimulationRunner.cc); same-host UTC/monotonic correspondence is checked. No
pose truth, vehicle transport or command exists in this adapter.
"""
from collections import deque
from datetime import datetime,timezone,timedelta
from threading import RLock
import time
from uuid import uuid4
from vehicle_autonomy.contracts.core.time import TimePoint


class SimulationGenerationClock:
    def __init__(self,world,*,subscribe=True):
        if not isinstance(world,str) or not world or any(c not in 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-' for c in world):raise ValueError('explicit owned world clock required')
        before=time.monotonic_ns();utc=time.time_ns();after=time.monotonic_ns()
        self.offset=before-utc;self.offset_low=before-utc;self.offset_high=after-utc;self.margin=2_000_000+(after-before);self.delayed=0;self.samples=deque(maxlen=2048);self.lock=RLock();self.fault=None;self.epoch=uuid4().hex;self.node=None
        self.topic='/world/'+world+'/clock'
        if subscribe:
            from gz.msgs10.clock_pb2 import Clock
            from gz.transport13 import Node
            self.node=Node()
            if not self.node.subscribe(Clock,self.topic,self._receive):raise RuntimeError('owned public Gazebo clock unavailable')
    def _receive(self,m):
        before=time.monotonic_ns();utc=time.time_ns();after=time.monotonic_ns()
        self.observe(m.sim.sec*1_000_000_000+m.sim.nsec,m.system.sec*1_000_000_000+m.system.nsec,after,utc,offset_interval=(before-utc,after-utc))
    def observe(self,simulation_ns,system_ns,received_ns,utc_now_ns,*,offset_interval=None):
        with self.lock:
            if self.fault:return
            low,high=offset_interval if offset_interval is not None else (received_ns-utc_now_ns,received_ns-utc_now_ns)
            baseline_low=self.offset_low if offset_interval is not None else self.offset
            baseline_high=self.offset_high if offset_interval is not None else self.offset
            if high<baseline_low-self.margin or low>baseline_high+self.margin:
                self.fault='host UTC/monotonic correspondence changed';return
            generated=system_ns+self.offset-self.margin
            if received_ns-generated<0:
                self.fault='Gazebo generation clock is in the future';return
            if received_ns-generated>100_000_000:
                # A late public sample supplies no fresh evidence. Keep the old
                # source watermark/age; only a genuinely current sample recovers.
                self.delayed+=1;return
            if self.samples:
                source,host=self.samples[-1]
                if simulation_ns<source or generated<host:self.fault='Gazebo clock epoch regressed';return
                if simulation_ns-source<10_000_000:return
            self.samples.append((simulation_ns,generated))
    def lower_bound(self,source_ns,now,*,strict_previous=False):
        with self.lock:
            if self.fault:raise ValueError(self.fault)
            if not self.samples or not 0<=now.monotonic_ns-self.samples[-1][1]<=100_000_000:raise ValueError('Gazebo generation clock unavailable/stale')
            if source_ns>self.samples[-1][0]+50_000_000:raise ValueError('source clock ahead of owned world')
            candidates=[host for sim,host in self.samples if sim<source_ns or not strict_previous and sim==source_ns]
            if not candidates:raise LookupError('original source predates bounded generation history')
            value=candidates[-1]
            return TimePoint(value,now.utc-timedelta(microseconds=(now.monotonic_ns-value)//1000),now.clock_domain_id)
    def close(self):
        if self.node:self.node.unsubscribe(self.topic);self.node=None
