"""Application-injected Action execution boundary; never a MAVLink writer."""
from __future__ import annotations
from concurrent.futures import Future
from typing import Protocol
from vehicle_autonomy.contracts.action import ActionContext, ActionSafety
from vehicle_autonomy.contracts.decision import EffectResult
from vehicle_autonomy.contracts.world.models import WorldSnapshot


class ActionAdmissionRejected(RuntimeError):
    """Admission failed with no new authority, commands, or physical side effects."""


class ActionDriver(Protocol):
    def context(self) -> ActionContext: ...
    def snapshot(self) -> WorldSnapshot | None: ...
    def open_scope(self, action_id: str, *, allow_send: bool, continuation_of: str | None, deadline) -> Future: ...
    def emit(self, action_id: str, envelope, *, cleanup: bool) -> Future: ...
    def effect_results(self, action_id: str) -> tuple[EffectResult, ...]: ...
    def begin_exit(self, action_id: str) -> None: ...
    def finish_scope(self, action_id: str, *, succeeded: bool) -> Future: ...
    def guard_status(self, action_id: str) -> ActionSafety | None: ...
